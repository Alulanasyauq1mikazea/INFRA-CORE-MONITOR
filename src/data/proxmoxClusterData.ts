export interface ProxmoxHostMetric {
  id: string;
  name: string;
  shortName: string;
  ip: string;
  status: 'online' | 'warning' | 'offline';
  cpuUsage: number; // %
  cpuCores: number;
  ramUsage: number; // %
  ramUsedGb: number;
  ramTotalGb: number;
  storageUsage: number; // %
  storageUsedTb: number;
  storageTotalTb: number;
  storagePoolName: string;
  vmsRunning: number;
  vmsTotal: number;
  uptime: string;
  colorName: string;
  accentText: string;
  barColor: string;
  storageBarColor: string;
  netRxMbps?: number;
  netTxMbps?: number;
}

