/**
 * Helper accessor functions and filtered subsets for Proxmox cluster state
 */
export const PROXMOX_OFFLINE_VMS = PROXMOX_ALL_VMS.filter(vm => vm.status === 'stopped');
export const PROXMOX_ONLINE_VMS = PROXMOX_ALL_VMS.filter(vm => vm.status === 'running');
export const PROXMOX_RUNNING_VMS = PROXMOX_ONLINE_VMS;

export const getStoredProxmoxVms = (): ProxmoxVmItem[] => {
  if (typeof window !== 'undefined') {
    try {
      const stored = localStorage.getItem('netwatch_custom_proxmox_vms');
      if (stored) {
        const parsed = JSON.parse(stored);
        if (Array.isArray(parsed) && parsed.length > 0) {
          return parsed;
        }
      }
    } catch {
      // fallback to static data
    }
  }
  return PROXMOX_ALL_VMS;
};

export const getDynamicProxmoxHosts = (): ProxmoxHostMetric[] => {
  return PROXMOX_CLUSTER_HOSTS;
};

export const getProxmoxVmsByHost = (hostId: string): ProxmoxVmItem[] => {
  return getStoredProxmoxVms().filter(vm => vm.proxmoxHost === hostId);
};

export const getProxmoxHostById = (hostId: string): ProxmoxHostMetric | undefined => {
  return PROXMOX_CLUSTER_HOSTS.find(host => host.id === hostId);
};


